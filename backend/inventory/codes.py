"""Codes printed on labels and read by barcode guns (pure functions, tested).

- Asset: the **Horizon ID**, "H" + 8 digits + 1 Luhn check digit (e.g. "H000012347"). The
  prefix only tells it apart from serial numbers: it encodes nothing (customer, warehouse…).
- Container: "C" + 8 digits + 1 Luhn check digit.
- Location: its own code ("SP01-EST-03-B"), starting with its warehouse's code.
- Warehouse: "<state or country><NN>" ("SP01"), generated by the system.

The numbers come from PostgreSQL sequences (no collisions); the check digit is verified on every
reading (RN-15).
"""

import re
from dataclasses import dataclass

ASSET_PREFIX = "H"
CONTAINER_PREFIX = "C"
DIGITS = 8

_SEQUENCED = re.compile(r"^([HC])(\d{8})(\d)$")
_LOCATION = re.compile(r"^[A-Z0-9]+(-[A-Z0-9]+)+$")


def luhn_digit(number: str) -> str:
    """Luhn check digit of a string of digits."""
    total = 0
    for position, char in enumerate(reversed(number)):
        digit = int(char)
        if position % 2 == 0:  # doubled: the rightmost digit before the check digit
            digit *= 2
            if digit > 9:
                digit -= 9
        total += digit
    return str((10 - total % 10) % 10)


def format_code(prefix: str, number: int) -> str:
    """format_code("H", 1234) → "H000012347"."""
    if not 0 < number < 10**DIGITS:
        raise ValueError("number out of range")
    digits = f"{number:0{DIGITS}d}"
    return f"{prefix}{digits}{luhn_digit(digits)}"


def normalize(text: str) -> str:
    """What a gun or a person typed: no spaces, uppercase."""
    return "".join((text or "").split()).upper()


@dataclass(frozen=True)
class ParsedCode:
    """A code read: its kind (asset | container | location | unknown), the normalized text,
    the sequence number (assets and containers) and whether the check digit is right."""

    kind: str
    code: str
    number: int | None = None
    valid: bool = True


def parse_code(text: str) -> ParsedCode:
    code = normalize(text)
    match = _SEQUENCED.match(code)
    if match:
        prefix, digits, check = match.groups()
        kind = "asset" if prefix == ASSET_PREFIX else "container"
        return ParsedCode(kind, code, int(digits), luhn_digit(digits) == check)
    if _LOCATION.match(code):
        return ParsedCode("location", code)
    return ParsedCode("unknown", code, valid=False)


def warehouse_code_prefix(state: str, country: str) -> str:
    """ "SP" for a Brazilian warehouse in São Paulo; the country ("BR", "US") without a state."""
    prefix = re.sub(r"[^A-Z0-9]", "", (state or "").upper()) or (country or "").upper()
    return prefix or "WH"


def next_warehouse_code(prefix: str, existing: set[str]) -> str:
    """The first free "<prefix><NN>" ("SP01", "SP02"…; three digits after 99)."""
    number = 1
    while True:
        code = f"{prefix}{number:02d}"
        if code not in existing:
            return code
        number += 1
