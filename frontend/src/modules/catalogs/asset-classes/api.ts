import type { ClassTranslation } from './names'
import { api, listQuery, type ListParams, type Paginated } from '@/api'
import type { SubVerticalOption } from '../verticals/api'

/** The four ratings that make up the remarketing rating (0–5 stars, half steps). */
export const REMARKETING_RATINGS = [
  'liquidity',
  'value_retention',
  'technology_renewal',
  'usage_breadth',
] as const

export type RemarketingRating = (typeof REMARKETING_RATINGS)[number]

export const SPEC_KINDS = ['text', 'number', 'boolean', 'choice', 'rating'] as const
export type SpecKind = (typeof SPEC_KINDS)[number]

/** A field of an asset class's specification template (e.g. "Operating hours", number, "h"). */
export interface SpecField {
  /** Stable identifier; empty for a field not saved yet (generated by the API) */
  key: string
  label: string
  /** text, number (with a unit), boolean (yes/no), choice (one of `options`), rating (0–5 stars) */
  kind: SpecKind
  /** Numbers only */
  unit: string
  required: boolean
  /** The list of a "choice" field (empty for the other kinds) */
  options: string[]
}

export interface AssetClass {
  id: number
  /** In English (the default language) */
  name: string
  plural_name: string
  /** Name and plural in other languages, optional (empty: English) — {"pt-br": {...}} */
  translations: Record<string, ClassTranslation>
  /** MDI icon name, e.g. "mdi-forklift" */
  icon: string
  /** Sub-vertical id (required) */
  sub_vertical: number
  /** The sub-vertical with its label ("Industry / Yellow line") and vertical (read-only) */
  sub_vertical_detail: SubVerticalOption
  /** 0–5 stars as decimal strings ("3.5"); not filled in = "0.0" */
  liquidity: string
  value_retention: string
  technology_renewal: string
  usage_breadth: string
  /** Average of the four ratings, computed by the API ("3.13"); read-only */
  remarketing_average: string
  /** Lowercase, no duplicates */
  keywords: string[]
  notes: string
  /** Fields described by every average price of this class; read-only (saveSpecTemplate) */
  spec_template: SpecField[]
  is_enabled: boolean
  created_at: string
  updated_at: string
}

export type AssetClassInput = Pick<
  AssetClass,
  | 'name'
  | 'plural_name'
  | 'translations'
  | 'icon'
  | RemarketingRating
  | 'keywords'
  | 'notes'
  | 'is_enabled'
> & {
  /** null only while editing a new asset class */
  sub_vertical: number | null
}

const BASE = '/catalogs/asset-classes/'

export function listAssetClasses(params: ListParams) {
  return api<Paginated<AssetClass>>(BASE + listQuery(params))
}

export function getAssetClass(id: number) {
  return api<AssetClass>(`${BASE}${id}/`)
}

export function createAssetClass(data: AssetClassInput) {
  return api<AssetClass>(BASE, { method: 'POST', body: JSON.stringify(data) })
}

export function updateAssetClass(id: number, data: AssetClassInput) {
  return api<AssetClass>(`${BASE}${id}/`, { method: 'PATCH', body: JSON.stringify(data) })
}

export function deleteAssetClass(id: number) {
  return api<void>(`${BASE}${id}/`, { method: 'DELETE' })
}

export function getSpecTemplate(assetClassId: number) {
  return api<{ fields: SpecField[] }>(`${BASE}${assetClassId}/spec-template/`)
}

/** Replaces the whole template. Errors come per field position ({"fields": {"1": [...]}}). */
export function saveSpecTemplate(assetClassId: number, fields: SpecField[]) {
  return api<{ fields: SpecField[] }>(`${BASE}${assetClassId}/spec-template/`, {
    method: 'PUT',
    body: JSON.stringify({ fields }),
  })
}
